import { clamp } from '../text';
import { RADIUS_CURVE } from './config';

/**
 * Monotone cubic (Fritsch–Carlson) interpolation through the control points:
 * smooth, non-linear, and guaranteed not to overshoot between points.
 */
function buildMonotone(points: [number, number][]) {
  const n = points.length;
  const xs = points.map((p) => p[0]);
  const ys = points.map((p) => p[1]);
  const d: number[] = [];
  for (let i = 0; i < n - 1; i++) d.push((ys[i + 1] - ys[i]) / (xs[i + 1] - xs[i]));
  const m: number[] = new Array(n);
  m[0] = d[0];
  m[n - 1] = d[n - 2];
  for (let i = 1; i < n - 1; i++) m[i] = d[i - 1] * d[i] <= 0 ? 0 : (d[i - 1] + d[i]) / 2;
  for (let i = 0; i < n - 1; i++) {
    if (d[i] === 0) {
      m[i] = m[i + 1] = 0;
      continue;
    }
    const a = m[i] / d[i];
    const b = m[i + 1] / d[i];
    const s = a * a + b * b;
    if (s > 9) {
      const t = 3 / Math.sqrt(s);
      m[i] = t * a * d[i];
      m[i + 1] = t * b * d[i];
    }
  }
  return (x: number) => {
    if (x <= xs[0]) return ys[0];
    if (x >= xs[n - 1]) return ys[n - 1];
    let i = 0;
    while (x > xs[i + 1]) i++;
    const h = xs[i + 1] - xs[i];
    const t = (x - xs[i]) / h;
    const t2 = t * t;
    const t3 = t2 * t;
    return (
      (2 * t3 - 3 * t2 + 1) * ys[i] + (t3 - 2 * t2 + t) * h * m[i] + (-2 * t3 + 3 * t2) * ys[i + 1] + (t3 - t2) * h * m[i + 1]
    );
  };
}

const defaultCurve = buildMonotone(RADIUS_CURVE);

export function makeRadiusFn(points: [number, number][] = RADIUS_CURVE) {
  const f = points === RADIUS_CURVE ? defaultCurve : buildMonotone(points);
  return (score: number, sizeScale = 1) => f(clamp(score, 0, 100)) * sizeScale;
}

/** Score (0..100) → grain radius in CSS px. */
export const scoreToRadius = makeRadiusFn();
